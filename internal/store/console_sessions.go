package store

import (
	"context"
	"errors"
	"strings"
	"time"

	"github.com/mateusz-klatt/iris/internal/consoleauth"
)

const (
	ConsoleSessionLifetime = 12 * time.Hour
	MaxConsoleSessions     = 16
)

// ConsoleSession contains safe inspection data. Digests, passwords and login keys
// have no place in a browser session projection.
type ConsoleSession struct {
	Account   ConsoleAccount `json:"account"`
	CreatedMS int64          `json:"created_ms"`
	ExpiresMS int64          `json:"expires_ms"`
}

func (t *transaction) consoleSession(digest []byte) (ConsoleSession, error) {
	var session ConsoleSession
	if len(digest) != 32 {
		return session, fail("unauthorized", "console session required")
	}
	var accountID string
	now := t.s.clock.Now().UnixMilli()
	err := t.row(`SELECT s.account_id,s.created_ms,s.expires_ms FROM ConsoleSession s JOIN ConsoleAccount a ON a.id=s.account_id
 WHERE s.digest=? AND s.expires_ms>? AND s.created_ms<=? AND s.auth_version=a.auth_version
 AND a.disabled=0 AND a.role IN ('operator','member')`, digest, now, now).Scan(&accountID, &session.CreatedMS, &session.ExpiresMS)
	if err != nil {
		return session, absent(err, "unauthorized", "console session is no longer valid")
	}
	session.Account, err = t.consoleAccount("id", accountID)
	return session, err
}

// ConsoleSessionAccount is trusted hub code's password-verification snapshot.
// Password work must finish outside the store lock before its version recheck.
func (s *Store) ConsoleSessionAccount(ctx context.Context, digest []byte) (ConsoleAccount, error) {
	var session ConsoleSession
	err := s.transact(ctx, func(t *transaction) error {
		var err error
		session, err = t.consoleSession(digest)
		return err
	})
	return session.Account, err
}

func (s *Store) ConsoleSessionInfo(ctx context.Context, digest []byte) (ConsoleSession, error) {
	var session ConsoleSession
	err := s.transact(ctx, func(t *transaction) error {
		var err error
		session, err = t.consoleSession(digest)
		return err
	})
	session.Account.PasswordHash, session.Account.LoginKey = "", ""
	return session, err
}

func (t *transaction) consoleSnapshot(before ConsoleAccount) (ConsoleAccount, error) {
	a, err := t.consoleAccount("id", before.ID)
	if err != nil {
		var domain *Error
		if errors.As(err, &domain) && domain.Code == "not_found" {
			return a, fail("unauthorized", "console credentials changed")
		}
		return a, err
	}
	if a.AuthVersion != before.AuthVersion || a.PasswordHash != before.PasswordHash {
		return a, fail("unauthorized", "console credentials changed")
	}
	return a, nil
}

func consoleNewHash(hash string) bool {
	return strings.HasPrefix(hash, "$argon2id$") && consoleauth.ValidateHash(hash) == nil
}

// IssueConsoleSession accepts only a digest generated by the trusted transport.
// Its snapshot recheck makes a reset/access edit during KDF work win permanently.
// A successful legacy upgrade revokes previous sessions and issues this one in
// the same transaction; a failed insertion leaves the old hash unchanged.
func (s *Store) IssueConsoleSession(ctx context.Context, before ConsoleAccount, digest []byte, upgradedHash string) (ConsoleAccount, error) {
	legacy := strings.HasPrefix(before.PasswordHash, "scrypt$")
	if len(digest) != 32 || consoleauth.ValidateHash(before.PasswordHash) != nil || legacy != (upgradedHash != "") || (upgradedHash != "" && !consoleNewHash(upgradedHash)) {
		return ConsoleAccount{}, fail("bad_request", "invalid console session material")
	}
	var account ConsoleAccount
	err := s.transact(ctx, func(t *transaction) error {
		var err error
		account, err = t.consoleSnapshot(before)
		if err != nil {
			return err
		}
		if !account.Enabled() {
			return fail("unauthorized", "console credentials changed")
		}
		if upgradedHash != "" {
			if err = t.changeConsolePassword(account.ID, upgradedHash, false); err != nil {
				return err
			}
		}
		now := s.clock.Now().UnixMilli()
		if _, err = t.exec("DELETE FROM ConsoleSession WHERE expires_ms<=?", now); err != nil {
			return err
		}
		// Stable digest ordering breaks ties when multiple logins share a clock tick.
		if _, err = t.exec(`DELETE FROM ConsoleSession WHERE digest IN (SELECT digest FROM ConsoleSession WHERE account_id=? ORDER BY created_ms DESC,digest DESC LIMIT -1 OFFSET ?)`, account.ID, MaxConsoleSessions-1); err != nil {
			return err
		}
		if _, err = t.exec("UPDATE ConsoleAccount SET last_login_ms=? WHERE id=?", now, account.ID); err != nil {
			return err
		}
		account, err = t.consoleAccount("id", account.ID)
		if err != nil {
			return err
		}
		if _, err = t.exec("INSERT INTO ConsoleSession(digest,account_id,auth_version,created_ms,expires_ms) VALUES(?,?,?,?,?)", digest, account.ID, account.AuthVersion, now, now+ConsoleSessionLifetime.Milliseconds()); err != nil {
			return err
		}
		t.notify = true
		return t.consoleAction(account.ID, account.ID, "login")
	})
	return account, err
}

// DeleteConsoleSession logs out an active session. An absent, expired or revoked
// session changes no state, so a same-origin stale-cookie retry is harmless.
func (s *Store) DeleteConsoleSession(ctx context.Context, digest []byte) error {
	return s.transact(ctx, func(t *transaction) error {
		session, err := t.consoleSession(digest)
		if err != nil {
			var domain *Error
			if errors.As(err, &domain) && domain.Code == "unauthorized" {
				return nil
			}
			return err
		}
		if _, err = t.exec("DELETE FROM ConsoleSession WHERE digest=?", digest); err != nil {
			return err
		}
		t.notify = true
		return t.consoleAction(session.Account.ID, session.Account.ID, "logout")
	})
}

func (t *transaction) changeConsolePassword(accountID, hash string, recoverOperator bool) error {
	query := "UPDATE ConsoleAccount SET password_hash=?,auth_version=auth_version+1,edit_revision=edit_revision+1 WHERE id=?"
	if recoverOperator {
		query = "UPDATE ConsoleAccount SET password_hash=?,role='operator',disabled=0,auth_version=auth_version+1,edit_revision=edit_revision+1 WHERE id=?"
	}
	if _, err := t.exec(query, hash, accountID); err != nil {
		return err
	}
	if recoverOperator {
		if _, err := t.exec("DELETE FROM ConsoleRepositoryAccess WHERE account_id=?", accountID); err != nil {
			return err
		}
	}
	if _, err := t.exec("DELETE FROM ConsoleSession WHERE account_id=?", accountID); err != nil {
		return err
	}
	t.notify = true
	return nil
}

func (s *Store) ChangeConsolePassword(ctx context.Context, p Principal, before ConsoleAccount, hash string) error {
	if !consoleNewHash(hash) {
		return fail("bad_request", "unsupported new password record")
	}
	return s.transact(ctx, func(t *transaction) error {
		if err := t.authorize(p, "ui_profile", Request{}); err != nil {
			return err
		}
		if t.console.ID != before.ID {
			return fail("forbidden", "only the current account may change its password")
		}
		if _, err := t.consoleSnapshot(before); err != nil {
			return err
		}
		if err := t.changeConsolePassword(before.ID, hash, false); err != nil {
			return err
		}
		return t.consoleAction(before.ID, before.ID, "password")
	})
}

// ProvisionConsoleOperator and RecoverConsoleOperator are trusted owner setup
// primitives. Only the owner-authenticated hub endpoint may expose them.
func (s *Store) ProvisionConsoleOperator(ctx context.Context, input ConsoleAccountInput) (ConsoleAccount, error) {
	if !consoleNewHash(input.PasswordHash) {
		return ConsoleAccount{}, fail("bad_request", "unsupported new password record")
	}
	input.Role, input.Disabled = "operator", false
	return s.createConsoleAccount(ctx, input, true)
}

func (t *transaction) consoleOwnerAction(target, action string) error {
	_, err := t.exec(`INSERT INTO ConsoleAction(actor_kind,actor_account_id,target_account_id,action,outcome,created_ms) VALUES('owner',NULL,?,?,'accepted',?)`, target, action, t.s.clock.Now().UnixMilli())
	return err
}

func (s *Store) RecoverConsoleOperator(ctx context.Context, before ConsoleAccount, hash string) (ConsoleAccount, error) {
	if !consoleNewHash(hash) {
		return ConsoleAccount{}, fail("bad_request", "unsupported new password record")
	}
	var account ConsoleAccount
	err := s.transact(ctx, func(t *transaction) error {
		current, err := t.consoleSnapshot(before)
		if err != nil {
			return err
		}
		if current.EditRevision != before.EditRevision {
			return fail("conflict", "console account changed; refresh before recovery")
		}
		if err = t.changeConsolePassword(before.ID, hash, true); err != nil {
			return err
		}
		if err = t.consoleOwnerAction(before.ID, "owner_recovery"); err != nil {
			return err
		}
		account, err = t.consoleAccount("id", before.ID)
		return err
	})
	return account, err
}

// AdmitConsoleFrame serializes scoped frame admission with every revocation.
// admit must only queue a frame without blocking; network I/O happens after this
// returns successfully. A frame admitted before revocation may be in transit.
func (s *Store) AdmitConsoleFrame(ctx context.Context, p Principal, admit func(map[string]any) error) error {
	return s.transact(ctx, func(t *transaction) error {
		if err := t.authorize(p, "ui_events", Request{}); err != nil {
			return err
		}
		frame, err := t.consoleEvents()
		if err != nil {
			return err
		}
		return admit(frame)
	})
}
